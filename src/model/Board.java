    /**
     * Array containing all 10 maze layouts. Index maps to a group of 5 levels
     * (e.g., index 0 = levels 1-5, index 1 = levels 6-10, ..., index 9 = levels
     * 46-50).
     */
    public static final int[][][] ALL_LAYOUTS = {
        LAYOUT_0, LAYOUT_1, LAYOUT_2, LAYOUT_3, LAYOUT_4,
        LAYOUT_5, LAYOUT_6, LAYOUT_7, LAYOUT_8, LAYOUT_9
    };

    /**
     * The active map grid; cell values change as Pac-Man eats dots.
     */
    private int[][] map;

    /**
     * Total number of dots (small dots + power pellets) at the start of the
     * level.
     */
    private int totalDots;

    /**
     * Index of the currently active layout (0-9).
     */
    private int layoutIndex;

    /**
     * Constructs a new Board using layout 0 and resets the map to its initial
     * state.
     */
    public Board() {
        this.layoutIndex = 0;
        reset();
    }

    /**
     * Switches to a new layout by index and resets the board. Called every 5
     * levels to advance to the next maze design.
     *
     * @param index layout index (0-9); wraps around if out of range
     */
    public void setLayout(int index) {
        this.layoutIndex = index % ALL_LAYOUTS.length; // wrap safely within bounds
        reset();
    }

    /**
     * Resets the board to the initial state of the current layout. Recounts the
     * total number of collectible dots.
     */
    public void reset() {
        int[][] template = ALL_LAYOUTS[layoutIndex];
        map = new int[rows()][cols()];
        totalDots = 0;

        for (int r = 0; r < rows(); r++) {
            for (int c = 0; c < cols(); c++) {
                map[r][c] = template[r][c]; // copy cell value from template
                if (map[r][c] == 0 || map[r][c] == 2) {
                    totalDots++; // count dots and power pellets
                }
            }
        }
    }

    /**
     * Returns the cell value at the given row and column. Returns 1 (wall) if
     * the position is out of bounds.
     *
     * @param r row index
     * @param c column index
     * @return cell value (0=dot, 1=wall, 2=pellet, 3=empty)
     */
    public int getCell(int r, int c) {
        if (r < 0 || r >= rows() || c < 0 || c >= cols()) {
            return 1; // treat out-of-bounds as a wall
        }
        return map[r][c];
    }

    /**
     * Sets the cell value at the given row and column. Does nothing if the
     * position is out of bounds.
     *
     * @param r row index
     * @param c column index
     * @param val new cell value to assign
     */
    public void setCell(int r, int c, int val) {
        if (r >= 0 && r < rows() && c >= 0 && c < cols()) {
            map[r][c] = val;
        }
    }

    /**
     * Returns whether the cell at (r, c) is a wall.
     *
     * @param r row index
     * @param c column index
     * @return true if the cell is a wall
     */
    public boolean isWall(int r, int c) {
        return getCell(r, c) == 1;
    }

    /**
     * Returns the number of rows in the current layout.
     *
     * @return row count
     */
    public int rows() {
        return ALL_LAYOUTS[layoutIndex].length;
    }

    /**
     * Returns the number of columns in the current layout.
     *
     * @return column count
     */
    public int cols() {
        return ALL_LAYOUTS[layoutIndex][0].length;
    }

    /**
     * Returns the total number of dots and power pellets at level start. Used
     * to detect level completion.
     *
     * @return total dot count
     */
    public int getTotalDots() {
        return totalDots;
    }

    /**
     * Returns the index of the currently active layout.
     *
     * @return layout index (0-9)
     */
    public int getLayoutIndex() {
        return layoutIndex;
    }
